import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const target = "src/contracts/api-error-codes.ts";

const spec = JSON.parse(
  readFileSync(resolve(root, "spec/openapi.json"), "utf8")
);
const codes: string[] =
  spec.components.schemas.ApiError.properties.error.properties.code.enum;
const streamOnly: string[] =
  spec.components.schemas.TurnStreamErrorEvent.properties.data.properties.code.enum.filter(
    (code: string) => !codes.includes(code)
  );
// `turnStreamErrorCodeSchema` in src/contracts/entities/sessions.ts names the
// stream-only codes by hand.
if (streamOnly.join() !== "turn_interrupted") {
  console.error(
    `spec/openapi.json lists the stream-only codes [${streamOnly.join(", ")}], and src/contracts/entities/sessions.ts types only turn_interrupted. Type them there, then change this check.`
  );
  process.exit(1);
}

const generated = `// Generated by \`npm run generate\` from spec/openapi.json. Do not edit by hand.

/** Every \`error.code\` the API contract lists. */
export const apiErrorCodes = [
${codes.map((code) => `  "${code}",`).join("\n")}
] as const;
`;

if (process.argv.includes("--check")) {
  if (readFileSync(resolve(root, target), "utf8") !== generated) {
    console.error(
      `${target} does not list the error codes of spec/openapi.json. Run \`npm run generate\` and commit the result.`
    );
    process.exit(1);
  }
} else {
  writeFileSync(resolve(root, target), generated);
}
